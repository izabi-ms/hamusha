export function t(key: string, locale: 'en' | 'bn' = 'en', params?: Record<string, string>): string {
  const entry = i18n[key];
  if (!entry) return key;
  let text = entry[locale] || entry.en || key;
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
    });
  }
  return text;
}

export function getLocaleFromPath(pathname: string): 'en' | 'bn' {
  if (pathname.startsWith('/bn/') || pathname === '/bn') return 'bn';
  return 'en';
}

export function localizePath(path: string, locale: 'en' | 'bn'): string {
  if (locale === 'bn') {
    return path === '/' ? '/bn' : `/bn${path}`;
  }
  return path;
}